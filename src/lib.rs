pub trait FakeAsia {
    fn fake_asia<R: Rng + ?Sized>(rng: &mut R) -> Self;

    fn fake() -> Self where Self: Sized {
        let mut rng = rand::thread_rng();
        Self::fake_asia(&mut rng)
    }
}

