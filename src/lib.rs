/// 使用指定BIN号生成银行卡号
fn generate_bank_card_with_bin<R: Rng + ?Sized>(rng: &mut R, bin: &str, total_len: usize) -> String {
    let body_len = total_len - bin.len() - 1; // 减去BIN和校验位
    let mut card = String::with_capacity(total_len);
    card.push_str(bin);
    for _ in 0..body_len {
        let digit: u32 = rng.gen_range(0..10);
        card.push(std::char::from_digit(digit, 10).unwrap());
    }
    let check = calculate_luhn_check_digit(&card);
    card.push(check);
    card
}


