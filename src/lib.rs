/// 计算Luhn校验位
/// 输入为不含校验位的数字字符串，返回校验位字符 ('0'-'9')
fn calculate_luhn_check_digit(partial: &str) -> char {
    let mut sum = 0;
    let mut double = true; // 从右往左，校验位左边第一位不翻倍，所以起始为true再翻转
    for c in partial.chars().rev() {
        let digit = c.to_digit(10).unwrap_or(0);
        let mut d = digit;
        if double {
            d *= 2;
            if d >= 10 {
                d -= 9;
            }
        }
        sum += d;
        double = !double;
    }
    let remainder = sum % 10;
    let check = if remainder == 0 { 0 } else { 10 - remainder };
    std::char::from_digit(check, 10).unwrap()
}

/// 验证银行卡号是否符合Luhn校验算法
pub fn is_valid_bank_card(card: &str) -> bool {
    if card.is_empty() || !card.chars().all(|c| c.is_ascii_digit()) || card.len() > 19 {
        return false;
    }
    let digits: Vec<u32> = card.chars()
        .filter_map(|c| c.to_digit(10))
        .collect();
    let mut sum = 0;
    let mut double = false; // 从右往左，最后一位（校验位）不翻倍
    for &d in digits.iter().rev() {
        let mut val = d;
        if double {
            val *= 2;
            if val >= 10 {
                val -= 9;
            }
        }
        sum += val;
        double = !double;
    }
    sum % 10 == 0
}

