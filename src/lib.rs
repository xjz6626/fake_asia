    #[test]
    fn test_id_check_code_algorithm_step_by_step() {
        // 手动逐步验证算法正确性
        // 输入: 11010119900307771
        let id_17 = "11010119900307771";
        let weights = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2];
        let check_codes = ['1', '0', 'X', '9', '8', '7', '6', '5', '4', '3', '2'];

        let sum: u32 = id_17
            .chars()
            .enumerate()
            .map(|(i, c)| c.to_digit(10).unwrap() * weights[i])
            .sum();
        // sum = 1*7 + 1*9 + 0*10 + 1*5 + 0*8 + 1*4 + 1*2 + 9*1 + 9*6 + 0*3 + 0*7 + 3*9 + 0*10 + 7*5 + 7*8 + 7*4 + 1*2
        //     = 7 + 9 + 0 + 5 + 0 + 4 + 2 + 9 + 54 + 0 + 0 + 27 + 0 + 35 + 56 + 28 + 2 = 238
        assert_eq!(sum, 238, "加权和计算错误");
        let remainder = sum % 11;
        assert_eq!(remainder, 7, "取余结果错误");
        let expected = check_codes[7]; // check_codes[7] = '5'
        assert_eq!(expected, '5', "校验码错误");

        let actual = calculate_id_check_code(id_17);
        assert_eq!(actual, expected, "函数计算结果与手动计算不一致");
    }

