/// 验证中国大陆身份证号码是否有效
/// 校验：位数、地区码、生日合理性、校验码
pub fn is_valid_chinese_id(id: &str) -> bool {
    // 1. 检查长度
    if id.len() != 18 && id.len() != 15 {
        return false;
    }

    if id.len() == 18 {
        return validate_18_digit_id(id);
    }

    // 15位旧版
    validate_15_digit_id(id)
}

fn validate_18_digit_id(id: &str) -> bool {
    let bytes = id.as_bytes();

    // 2. 前17位必须是数字
    for i in 0..17 {
        if !bytes[i].is_ascii_digit() {
            return false;
        }
    }
    // 第18位是数字或X
    if !(bytes[17].is_ascii_digit() || bytes[17] == b'X') {
        return false;
    }

    // 3. 检查地区码（前2位在有效范围内）
    let province_prefix = &id[..2];
    let valid_prefixes: Vec<&str> = data::PROVINCE_TO_ID_PREFIX
        .iter()
        .map(|(_, p)| *p)
        .collect();
    if !valid_prefixes.contains(&province_prefix) {
        return false;
    }

    // 4. 检查生日
    let year: u32 = id[6..10].parse().unwrap_or(0);
    let month: u32 = id[10..12].parse().unwrap_or(0);
    let day: u32 = id[12..14].parse().unwrap_or(0);
    if year < 1900 || year > 2100 || month < 1 || month > 12 || day < 1 || day > 31 {
        return false;
    }
    let max_day = match month {
        2 => {
            let is_leap = (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0);
            if is_leap { 29 } else { 28 }
        }
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    };
    if day > max_day {
        return false;
    }

    // 5. 校验码验证
    let expected_check = calculate_id_check_code(&id[..17]);
    let actual_check = id.chars().last().unwrap();
    expected_check == actual_check
}

fn validate_15_digit_id(id: &str) -> bool {
    let bytes = id.as_bytes();

    // 前15位必须全是数字
    for i in 0..15 {
        if !bytes[i].is_ascii_digit() {
            return false;
        }
    }

    // 检查地区码
    let province_prefix = &id[..2];
    let valid_prefixes: Vec<&str> = data::PROVINCE_TO_ID_PREFIX
        .iter()
        .map(|(_, p)| *p)
        .collect();
    if !valid_prefixes.contains(&province_prefix) {
        return false;
    }

    // 检查生日 (YYMMDD)
    let yy: u32 = id[6..8].parse().unwrap_or(0);
    let month: u32 = id[8..10].parse().unwrap_or(0);
    let day: u32 = id[10..12].parse().unwrap_or(0);
    // 15位身份证的年份范围 00-99，对应 1900-1999 或更宽泛范围
    if month < 1 || month > 12 || day < 1 || day > 31 {
        return false;
    }
    let year_4 = if yy <= 50 { 2000 + yy } else { 1900 + yy };
    let max_day = match month {
        2 => {
            let is_leap = (year_4 % 4 == 0 && year_4 % 100 != 0) || (year_4 % 400 == 0);
            if is_leap { 29 } else { 28 }
        }
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    };
    if day > max_day {
        return false;
    }

    true
}

/// 生成中国车牌号
/// 格式：省份简称 + 字母 + 5位数字/字母组合
pub fn chinese_license_plate<R: Rng + ?Sized>(rng: &mut R) -> String {
    let province = data::LICENSE_PLATE_PROVINCES.choose(rng).unwrap_or(&("京", "北京")).0;
    let letter = (b'A' + rng.gen_range(0..26)) as char;
    
    // 生成5位数字/字母组合（通常前几位是字母，后面是数字）
    let mut plate_num = String::new();
    for i in 0..5 {
        if i < 2 && rng.gen_bool(0.3) {
            // 前面可能是字母
            plate_num.push((b'A' + rng.gen_range(0..26)) as char);
        } else {
            // 主要是数字
            plate_num.push_str(&rng.gen_range(0..=9).to_string());
        }
    }
    
    format!("{}{}{}", province, letter, plate_num)
}

/// 生成中国新能源车牌号
/// 格式：省份简称 + 字母 + D/F + 5位数字/字母
/// D = 纯电动, F = 非纯电动（混合动力等）
pub fn chinese_new_energy_license_plate<R: Rng + ?Sized>(rng: &mut R) -> String {
    let province = data::LICENSE_PLATE_PROVINCES.choose(rng).unwrap_or(&("京", "北京")).0;
    let letter = (b'A' + rng.gen_range(0..26)) as char;
    let energy_type = if rng.gen_bool(0.6) { 'D' } else { 'F' };
    
    // 新能源车牌后5位：最后一位是数字，前面可以是字母或数字
    let mut plate_num = String::new();
    for i in 0..5 {
        if i == 4 {
            plate_num.push(rng.gen_range(0..=9).to_string().chars().next().unwrap());
        } else if rng.gen_bool(0.4) {
            plate_num.push((b'A' + rng.gen_range(0..26)) as char);
        } else {
            plate_num.push(rng.gen_range(0..=9).to_string().chars().next().unwrap());
        }
    }
    
    format!("{}{}{}{}", province, letter, energy_type, plate_num)
}

